def check_long(actual, ref, name, stride=32):
    """Compare a long time-domain output through its slice and full-length reductions"""
    a = actual.cpu().numpy()
    assert_close(a[..., ::stride], ref[f"{name}/slice"], RTOL32, f"{name}/slice")
    a128 = a.astype(np.complex128)
    energy = np.sum(np.abs(a128) ** 2, axis=-1)
    total = np.sum(a128, axis=-1)
    # Energy over 2176 samples; reductions accumulate single-precision rounding
    assert_close(energy, ref[f"{name}/energy"], 5e-6, f"{name}/energy")
    assert_close(total, ref[f"{name}/sum"], 5e-6, f"{name}/sum")


def test_real_beamspace(ref, real_data):
    h, rx_cb, tx_cb, rx_axis, tx_axis = real_data
    layer = bf.Beamspace(transmit_axis=tx_axis, receive_axis=rx_axis)
    check_long(layer(torch.from_numpy(h), torch.from_numpy(rx_cb), torch.from_numpy(tx_cb)),
               ref, "real/beamspace_full")
    check_long(layer(torch.from_numpy(h), torch.from_numpy(rx_cb[:, :1]), torch.from_numpy(tx_cb[:, :1])),
               ref, "real/beamspace_siso")


@pytest.mark.parametrize("ortho", [True, False])
@pytest.mark.parametrize("k", [1, 4])
def test_real_beam_selection(ref, real_data, ortho, k):
    h, rx_cb, tx_cb, rx_axis, tx_axis = real_data
    h_tx = bf.Beamspace(transmit_axis=tx_axis)(torch.from_numpy(h), torch.from_numpy(tx_cb))
