@pytest.mark.parametrize("name", cases.CHANNEL_POWER_KWARGS)
def test_signal_power_sum(ref, name):
    """Default behavior (sum over axes) against TF ``channel_power`` (moved from beamforming)"""
    out = signal_power(torch.from_numpy(cases.channel_power_input()), **cases.CHANNEL_POWER_KWARGS[name])
    assert_close(out, ref[f"channel_power/{name}"], RTOL32, name)


@pytest.mark.parametrize("name", cases.BEAM_SELECTION_CASES)
def test_beam_selection(ref, name):
    case = cases.BEAM_SELECTION_CASES[name]
    h = cases.beam_selection_input(case)
    out = bf.BeamSelection(**case["kwargs"])(torch.from_numpy(h))
    expected = ref[f"beam_selection/{name}"]
    if case["kwargs"].get("normalize", True):
        # Same selection, then an identical scaling
        assert_close(out, expected, RTOL32, name)
    else:
        # Pure selection: bitwise identical values, which also asserts identical tie-breaking
        assert_equal(out, expected, name)


@pytest.mark.parametrize("name", cases.beamspace_cases())
def test_beamspace(ref, name):
    case = cases.beamspace_cases()[name]
    double = case["h"].dtype == np.complex128
    layer = bf.Beamspace(transmit_axis=case["tx_axis"], receive_axis=case["rx_axis"],
                         precision="double" if double else None)
    inputs = [torch.from_numpy(case["h"])]
    inputs += [torch.from_numpy(case[k]) for k in ("rx", "tx") if case[k] is not None]
    out = layer(*inputs)
    assert out.dtype == (torch.complex128 if double else torch.complex64)
    assert_close(out, ref[f"beamspace/{name}"], RTOL64 if double else RTOL32, name)


