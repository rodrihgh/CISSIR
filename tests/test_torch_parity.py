"""
Numerical parity between the PyTorch implementation and the former TensorFlow implementation.

The TensorFlow reference outputs in ``data/tf_reference.npz`` were generated by ``gen_tf_reference.py``
from the last TensorFlow-based commit. Run from the project root with:

    pytest tests -v
"""

import sys
from pathlib import Path

import numpy as np
import pytest
import torch

sys.path.insert(0, str(Path(__file__).parent))
import cases  # noqa: E402
from cissir import adc, beamforming as bf, raytracing as rtr  # noqa: E402
from cissir.sigproc import signal_power  # noqa: E402
from cissir.utils import axes_tuple  # noqa: E402

REF_PATH = Path(__file__).parent/"data"/"tf_reference.npz"

# Relative tolerance in terms of the largest magnitude of the reference (single precision)
RTOL32 = 2e-6
RTOL64 = 1e-12


@pytest.fixture(scope="module")
def ref():
    with np.load(REF_PATH) as d:
        return {k: d[k] for k in d.files}


def assert_close(actual, expected, rtol, name=""):
    actual = actual.detach().cpu().numpy() if isinstance(actual, torch.Tensor) else np.asarray(actual)
    assert actual.shape == expected.shape, f"{name}: shape {actual.shape} != {expected.shape}"
    assert actual.dtype == expected.dtype, f"{name}: dtype {actual.dtype} != {expected.dtype}"
    scale = max(np.max(np.abs(expected)), np.finfo(np.float32).tiny)
    err = np.max(np.abs(actual - expected))
    assert err <= rtol * scale, f"{name}: max abs error {err:.3e} > {rtol * scale:.3e} (scale {scale:.3e})"


def assert_equal(actual, expected, name=""):
    actual = actual.detach().cpu().numpy() if isinstance(actual, torch.Tensor) else np.asarray(actual)
    assert actual.shape == expected.shape, f"{name}: shape {actual.shape} != {expected.shape}"
    np.testing.assert_array_equal(actual, expected, err_msg=name)


