def test_top_k_tie_breaking_matches_tensorflow():
    """``torch.topk`` breaks ties differently from ``tf.math.top_k``: lowest index first is required"""
    x = torch.tensor([[1., 3., 3., 3., 0., 3.]])
    assert bf.top_k_indices(x, 3).tolist() == [[1, 2, 3]]


