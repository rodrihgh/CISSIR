def test_beam_selection_compile():
    """The block must work under ``torch.compile`` (Sionna convention) and agree with eager mode"""
    case = cases.BEAM_SELECTION_CASES["L30_rand_ortho_k4_norm"]
    h = torch.from_numpy(cases.beam_selection_input(case))
    sel = bf.BeamSelection(**case["kwargs"])
    eager = sel(h)
    try:
        compiled = torch.compile(sel)(h)
    except Exception as e:  # e.g. missing C++ toolchain
        pytest.skip(f"torch.compile unavailable: {type(e).__name__}")
    assert_equal(compiled, eager.numpy())


